// Property Documentation
// ------------

// NOTE • Generates the style files that mirror the TS design tokens, so the
// tokens in src/theme stay the single source of truth:
//   src/css/tokens.css              → every token as a CSS custom property on :root
//   src/css/tackl/_breakpoints.scss → $breakpoints map + bp() / bpd() mixins
//   src/css/tackl/_grid.scss        → columns, gutters, max width, design widths
// Runs before dev/build/storybook. `--check` exits non-zero when a generated
// file is stale (used by the pre-commit hook) without writing anything.

// Imports
// ------------
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { borderRadiusValues } from '@theme/borderRadius';
import { baseColors } from '@theme/colors';
import { toVarDeclarations } from '@theme/cssVariables';
import { easingValues } from '@theme/easing';
import { fontFamilies, fontWeights } from '@theme/fonts/values';
import { gapValues } from '@theme/gap';
import { grid } from '@theme/grid';
import { spaceValues } from '@theme/space';
import { timeValues } from '@theme/time';

// Constants
// ------------
const ROOT = path.resolve(import.meta.dir, '..');
const IS_CHECK = process.argv.includes('--check');

// NOTE • Keeps bp(m) and bpd(m) from both matching at exactly the breakpoint
const DOWN_OFFSET = 0.02;

const banner = (comment: (line: string) => string) =>
	[
		'GENERATED by scripts/build-styles.ts — do not edit.',
		'Change the tokens in src/theme, then run `bun run styles`.',
	]
		.map(comment)
		.join('\n');

const cssBanner = `/* ${banner(line => line).replace('\n', '\n   ')} */`;
const scssBanner = banner(line => `// ${line}`);

// Helpers
// ------------
const indent = (text: string) =>
	text
		.split('\n')
		.map(line => `\t${line}`)
		.join('\n');

const sassMap = (values: Record<string, string | number>) =>
	`(\n${Object.entries(values)
		.map(([key, value]) => `\t${key}: ${value},`)
		.join('\n')}\n)`;

// Files
// ------------
const tokensCss = () => {
	const declarations = [
		...Object.entries(baseColors).map(([group, values]) => toVarDeclarations(group, values)),
		toVarDeclarations('space', spaceValues),
		toVarDeclarations('gap', gapValues),
		toVarDeclarations('br', borderRadiusValues),
		toVarDeclarations('easing', easingValues),
		toVarDeclarations('time', timeValues),
		toVarDeclarations('font', fontFamilies),
		toVarDeclarations('weight', fontWeights),
	].join('\n');

	return `${cssBanner}

:root {
${indent(declarations)}
}
`;
};

const breakpointsScss = () => {
	const down = Object.fromEntries(
		Object.entries(grid.breakpoints).map(([key, value]) => [key, `${parseFloat(value) - DOWN_OFFSET}px`])
	);

	return `${scssBanner}

@use 'sass:map';

$breakpoints: ${sassMap(grid.breakpoints)};

$breakpoints-down: ${sassMap(down)};

// Mobile-first: styles from this breakpoint up
@mixin bp($key) {
	@media (min-width: map.get($breakpoints, $key)) {
		@content;
	}
}

// The rare max-width case: styles below this breakpoint
@mixin bpd($key) {
	@media (max-width: map.get($breakpoints-down, $key)) {
		@content;
	}
}
`;
};

const gridScss = () => `${scssBanner}

$columns: ${sassMap(grid.columns)};

$gutters: ${sassMap(grid.gutter)};

$grid-max: ${grid.maxSize};

$design-widths: ${sassMap(grid.design)};
`;

const FILES: Record<string, () => string> = {
	'src/css/tokens.css': tokensCss,
	'src/css/tackl/_breakpoints.scss': breakpointsScss,
	'src/css/tackl/_grid.scss': gridScss,
};

// Run
// ------------
const read = (file: string) => {
	try {
		return readFileSync(file, 'utf8');
	} catch {
		return null;
	}
};

const stale = Object.entries(FILES).filter(([file, build]) => {
	const target = path.join(ROOT, file);
	const content = build();
	if (read(target) === content) return false;
	if (!IS_CHECK) writeFileSync(target, content);
	return true;
});

if (IS_CHECK && stale.length) {
	console.error(`Generated styles are stale: ${stale.map(([file]) => file).join(', ')}\nRun \`bun run styles\`.`);
	process.exit(1);
}

if (!IS_CHECK) console.log(stale.length ? `Generated ${stale.map(([file]) => file).join(', ')}` : 'Styles up to date');
